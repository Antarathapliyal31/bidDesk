@router.get("/api/runs/{run_id}/source.pdf")
async def get_run_source_pdf(request: Request, run_id: str) -> FileResponse:
    run = await repo.get_run(_db(request), run_id=run_id)
    if run is None:
        raise RunNotFoundError(run_id=run_id)
    if run["input_kind"] != InputKind.pdf.value:
        # text-paste runs have no source PDF
        raise RunNotFoundError(run_id=run_id)
    doc = await repo.get_document(_db(request), run_id=run_id)
    if doc is None:
        raise RunNotFoundError(run_id=run_id)
    path = Path(doc["stored_path"])
    if not path.exists():
        raise RunNotFoundError(run_id=run_id)
    return FileResponse(
        path, media_type="application/pdf", filename=doc["filename"] or "source.pdf"
    )


