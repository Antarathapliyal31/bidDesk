@router.get("/api/runs/{run_id}")
async def get_run_detail(request: Request, run_id: str) -> dict[str, Any]:
    """Nested response per API_CONTRACT: `input`, `project`,
    `branch` are objects; the hook flattens at the boundary."""

    run = await repo.get_run(_db(request), run_id=run_id)
    if run is None:
        raise RunNotFoundError(run_id=run_id)

    agent = await repo.get_bid(_db(request), run_id=run_id, kind="agent")
    draft = await repo.get_bid(_db(request), run_id=run_id, kind="draft")
    final = await repo.get_bid(_db(request), run_id=run_id, kind="final")
    current = final or draft or agent

    # branch metadata for the nested `branch` block.
    import sqlite3

    conn = sqlite3.connect(f"file:{_settings(request).catalog_db_path}?mode=ro", uri=True)
    try:
        brow = conn.execute(
            "SELECT id, name, tax_rate_ppm FROM branches WHERE id = ?",
            (run["branch_id"],),
        ).fetchone()
    finally:
        conn.close()
    if brow is None:
        # Server invariant: POST /api/runs rejects unknown branches,
        # so a run row with a missing branch means the catalog
        # changed under us. Fail loudly rather than fake a block.
        raise RuntimeError(f"run {run_id!r} references unknown branch {run['branch_id']!r}")
    branch_block = {"id": brow[0], "name": brow[1], "tax_rate_ppm": int(brow[2])}

    doc = await repo.get_document(_db(request), run_id=run_id)
    page_count = doc["page_count"] if doc is not None else None

    due_date_text = None
    project_from_bid = current or agent or draft
    if project_from_bid is not None:
        proj = project_from_bid["data"].get("project") or {}
        due_date_text = proj.get("due_date_text")

    return {
        "id": run["id"],
        "created_at": run["created_at"],
        "finished_at": run["finished_at"],
        "finalized_at": final["finalized_at"] if final else None,
        "status": run["status"],
        "outcome": run["outcome"],
        "outcome_detail": run["outcome_detail"],
        "input": {
            "kind": run["input_kind"],
            "name": run["input_name"],
            "page_count": page_count,
        },
        "project": {
            "name": run["project_name"],
            "due_date_text": due_date_text,
        },
        "branch": branch_block,
        "tokens_in": run["tokens_in"],
        "tokens_out": run["tokens_out"],
        "bid": current["data"] if current else None,
        "agent_bid": agent["data"] if agent else None,
        "diff": None,
    }


