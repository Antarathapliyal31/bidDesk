@router.get("/api/runs")
async def list_runs(
    request: Request,
    status: str | None = Query(default=None),
    cursor: str | None = Query(default=None),
    limit: int = Query(default=20, ge=1),
) -> dict[str, Any]:
    clamped = min(max(limit, 1), 100)
    cursor_created_at: str | None = None
    cursor_id: str | None = None
    if cursor:
        try:
            decoded = json.loads(cursor)
            cursor_created_at = str(decoded["c"])
            cursor_id = str(decoded["i"])
        except Exception as exc:
            raise InvalidInputError(f"invalid cursor: {exc}") from exc

    # Fetch one extra to know whether there's a next page.
    rows = await repo.list_runs_page(
        _db(request),
        status=status,
        cursor_created_at=cursor_created_at,
        cursor_id=cursor_id,
        limit=clamped + 1,
    )
    has_more = len(rows) > clamped
    page = rows[:clamped]
    items: list[dict[str, Any]] = []
    branch_names = {b.id: b.name for b in await _list_branches(request)}
    for row in page:
        bid_summary = await _list_bid_summary(request, run_id=row["id"])
        items.append(
            {
                "id": row["id"],
                "status": row["status"],
                "outcome": row["outcome"],
                "input_kind": row["input_kind"],
                "input_name": row["input_name"],
                "project_name": row["project_name"],
                "branch_name": branch_names.get(row["branch_id"], row["branch_id"]),
                "priced_lines": bid_summary.get("priced_lines"),
                "open_flags": bid_summary.get("open_flags"),
                "total_cents": bid_summary.get("total_cents"),
                "created_at": row["created_at"],
                "finalized_at": _finalized_at_from_bid(bid_summary),
                "diff": None,  # Phase-9 diff lands when needed
            }
        )
    next_cursor = (
        json.dumps({"c": page[-1]["created_at"], "i": page[-1]["id"]})
        if has_more and page
        else None
    )
    return {"items": items, "next_cursor": next_cursor}


async def _list_branches(request: Request) -> list[BranchInfo]:
    import sqlite3

    conn = sqlite3.connect(f"file:{_settings(request).catalog_db_path}?mode=ro", uri=True)
    try:
        rows = conn.execute("SELECT id, name, tax_rate_ppm FROM branches").fetchall()
    finally:
        conn.close()
    return [BranchInfo(id=r[0], name=r[1], tax_rate_ppm=int(r[2])) for r in rows]


async def _list_bid_summary(request: Request, *, run_id: str) -> dict[str, Any]:
    """Pull the current draft (or agent) bid's totals for the
    history-row summary. None if no bid yet."""

    draft = await repo.get_bid(_db(request), run_id=run_id, kind="draft")
    agent = await repo.get_bid(_db(request), run_id=run_id, kind="agent")
    final = await repo.get_bid(_db(request), run_id=run_id, kind="final")
    pick = final or draft or agent
    if pick is None:
        return {}
    totals = pick["data"].get("totals") or {}
    out = {
        "priced_lines": totals.get("priced_lines"),
        "open_flags": totals.get("open_flags"),
        "total_cents": totals.get("total_cents"),
    }
    if final is not None:
        out["finalized_at"] = final["finalized_at"]
    return out


def _finalized_at_from_bid(bid_summary: dict[str, Any]) -> str | None:
    return bid_summary.get("finalized_at")


