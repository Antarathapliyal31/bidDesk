"""`/api/runs` routes: create, list, detail, SSE stream, source.pdf,
PATCH bid, finalize. SPEC §13 + `docs/API_CONTRACT.md`.

Design notes:
  - All writes through `repo.py`; no raw SQL in routes.
  - Every non-2xx raises an `ApiError` subclass so the envelope
    is generated by the global exception handler.
  - The SSE handoff (replay then live) uses `EventBus.subscribe`
    first, then drains everything with `id > last_event_id`
    from the DB, then yields subscription events whose
    `id > last_delivered_id`. This covers the "no gaps and no
    duplicates" invariant.
"""

