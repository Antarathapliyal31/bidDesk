import { CheckCircle2Icon, FlagIcon, GitPullRequestClosedIcon } from "lucide-react";

import type { RunViewState } from "@/lib/runReducer";

/**
 * "Bid ready" placeholder shown after `bid.ready` lands. Phase 8
 * replaces this with the editable `BidWorkspace` (SPEC §11.2) —
 * LinesTable, ReviewQueue, TotalsBar, FinalizeBar, etc.
 *
 * For now, this surfaces the summary numbers from the reducer so
 * the demo visibly transitions from Live → Bid when the run
 * finishes, and so an interviewer sees exactly what the server
 * said was ready.
 */
type Props = {
  state: RunViewState;
};

export function BidWorkspacePlaceholder({ state }: Props) {
  const ready = state.bidReady;
  if (!ready) {
    return (
      <div className="mx-auto max-w-5xl px-6 py-10 text-sm text-muted-foreground">
        Waiting for the bid to finish…
      </div>
    );
  }

  // "Priced" = status matched OR substitute (the two statuses that
  // carry a real unit_price_cents). no_match / skipped / failed /
  // timeout rows have a `priced` field set but aren't priced in any
  // commercial sense, so counting them here would double-count what
  // ReviewQueue + the Ext. column already surface.
  const pricedCount = Object.values(state.items).filter(
    (i) => i.priced?.status === "matched" || i.priced?.status === "substitute",
  ).length;

  return (
    <div className="mx-auto max-w-5xl space-y-6 px-6 py-10">
      <div className="flex items-start gap-3 rounded-md border border-border bg-card p-5">
        <CheckCircle2Icon className="mt-0.5 size-5 shrink-0 text-done-green-text" aria-hidden />
        <div className="min-w-0 flex-1">
          <h2 className="text-lg font-semibold">Bid ready</h2>
          <p className="mt-1 text-sm text-muted-foreground">
            Revision {ready.revision} ·{" "}
            {ready.generated_by === "orchestrator"
              ? "generated by the orchestrator"
              : "assembled by fallback (orchestrator budget reached)"}
            . The full editable workspace arrives in Phase 8.
          </p>
        </div>
      </div>

      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <SummaryCard label="Priced lines" value={pricedCount} />
        <SummaryCard
          label="Open flags"
          value={ready.open_flags}
          tone={ready.open_flags > 0 ? "warn" : "ok"}
          icon={<FlagIcon className="size-4" aria-hidden />}
        />
        <SummaryCard
          label="Conflicts"
          value={state.conflicts.length}
          tone={state.conflicts.length > 0 ? "warn" : "ok"}
          icon={<GitPullRequestClosedIcon className="size-4" aria-hidden />}
        />
      </div>
    </div>
  );
}

function SummaryCard({
  label,
  value,
  tone = "ok",
  icon,
}: {
  label: string;
  value: number;
  tone?: "ok" | "warn";
  icon?: React.ReactNode;
}) {
  return (
    <div className="rounded-md border border-border bg-card p-4">
      <div className="flex items-center gap-2 text-xs font-medium uppercase tracking-wide text-muted-foreground">
        {icon}
        {label}
      </div>
      <p
        className={
          "mt-2 tabular text-2xl font-semibold " +
          (tone === "warn" && value > 0 ? "text-warn-amber-text" : "text-foreground")
        }
      >
        {value}
      </p>
    </div>
  );
}
