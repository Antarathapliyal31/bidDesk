# GET /api/runs/{id}/stream  — SSE replay → live
# ---------------------------------------------------------------------------


@router.get("/api/runs/{run_id}/stream")
async def stream_run_events(request: Request, run_id: str) -> StreamingResponse:
    """SSE stream — replay DB events after `Last-Event-ID` then
    switch to live. Uses `EventBus.stream_after` which subscribes
    FIRST (so no live event is dropped during the DB drain) and
    dedupes by id on the handoff. Heartbeat `:` comment every
    15 s; closes after `run.finished`."""

    run = await repo.get_run(_db(request), run_id=run_id)
    if run is None:
        raise RunNotFoundError(run_id=run_id)

    last_event_id = 0
    header = request.headers.get("Last-Event-ID")
    if header:
        try:
            last_event_id = max(0, int(header))
        except ValueError:
            last_event_id = 0
    q_after = request.query_params.get("after_id")
    if q_after:
        with contextlib.suppress(ValueError):
            last_event_id = max(last_event_id, int(q_after))

    bus = _bus(request)

    async def _event_stream():
        heartbeat_task: asyncio.Task[Any] | None = None
        gen = bus.stream_after(run_id, after_id=last_event_id)
        try:
            while True:
                next_task = asyncio.ensure_future(gen.__anext__())
                if heartbeat_task is None or heartbeat_task.done():
                    heartbeat_task = asyncio.ensure_future(asyncio.sleep(15.0))
                done, _pending = await asyncio.wait(
                    {next_task, heartbeat_task},
                    return_when=asyncio.FIRST_COMPLETED,
                )
                if next_task in done:
                    try:
                        event = next_task.result()
                    except StopAsyncIteration:
                        return
                    yield _format_sse_event(event)
                    if event.get("type") == "run.finished":
                        return
                else:
                    # heartbeat fired without a new event
                    next_task.cancel()
                    yield ": heartbeat\n\n"
                    heartbeat_task = None
        finally:
            await gen.aclose()

    return StreamingResponse(
        _event_stream(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


def _format_sse_event(event: dict[str, Any]) -> str:
    """Serialise one event dict (from EventBus.stream_after) into
    the on-the-wire SSE frame. The `id:` field matches the DB id
    so `Last-Event-ID` resumes deterministically."""

    eid = int(event["id"])
    return f"id: {eid}\nevent: {event['type']}\ndata: {json.dumps(event)}\n\n"


