import { AlertTriangleIcon, FileClockIcon, FileTextIcon } from "lucide-react";

import type { Bid } from "@/api";
import { computeBidDiff } from "@/lib/bidDiff";

/**
 * Bid document header (SPEC §11.2, §11.5 "document feel"): project
 * name, branch, generated-by note, partial-run banner.
 *
 * `partial_reasons` — when the server returned `generated_by =
 * fallback` or the run's status is "partial" — we surface the list
 * so the estimator knows what the agent couldn't finish.
 */
type Props = {
  projectName: string | null;
  branchName: string | null;
  branchId: string | null;
  bid: Bid;
  agentBid: Bid | null;
};

export function BidHeader({ projectName, branchName, branchId, bid, agentBid }: Props) {
  const isFallback = bid.generated_by === "fallback";
  const diff = computeBidDiff(bid, agentBid);
  const hasDiff = diff.changed + diff.added + diff.deleted + diff.accepted > 0;
  return (
    <header className="space-y-3">
      <div className="flex items-start justify-between gap-6">
        <div className="min-w-0">
          <h2 className="truncate text-2xl font-semibold tracking-tight">
            {projectName ?? "Materials bid"}
          </h2>
          <p className="mt-1 text-xs text-muted-foreground">
            {branchName ?? "—"}
            {branchId ? ` · ${branchId}` : ""}
            {" · Revision "}
            {bid.revision}
            {" · "}
            {bid.kind === "final" ? "Final" : bid.kind === "agent" ? "Agent" : "Draft"}
          </p>
          {hasDiff ? (
            <p
              className="mt-1 text-xs text-muted-foreground"
              aria-label="Diff versus the agent's original bid"
            >
              vs agent:{" "}
              <span className="tabular text-foreground">{diff.changed}</span> changed ·{" "}
              <span className="tabular text-foreground">{diff.added}</span> added ·{" "}
              <span className="tabular text-foreground">{diff.deleted}</span> deleted ·{" "}
              <span className="tabular text-foreground">{diff.accepted}</span> accepted
            </p>
          ) : null}
        </div>
        <div className="flex shrink-0 items-center gap-2 text-xs text-muted-foreground">
          {isFallback ? (
            <FileClockIcon className="size-3.5" aria-hidden />
          ) : (
            <FileTextIcon className="size-3.5" aria-hidden />
          )}
          {isFallback ? "Assembled by fallback" : "Generated by orchestrator"}
        </div>
      </div>

      {bid.partial_reasons.length > 0 ? (
        <div className="flex items-start gap-2 rounded-md border border-warn-amber/30 bg-warn-amber/10 px-3 py-2 text-xs text-warn-amber-text">
          <AlertTriangleIcon className="mt-0.5 size-3.5 shrink-0" aria-hidden />
          <div className="min-w-0">
            <p className="font-medium">Partial result</p>
            <ul className="mt-1 list-disc space-y-0.5 pl-4">
              {bid.partial_reasons.map((r, i) => (
                <li key={i}>{r}</li>
              ))}
            </ul>
          </div>
        </div>
      ) : null}

      {bid.summary ? (
        <p className="rounded-md border border-border bg-muted/30 px-3 py-2 text-xs text-foreground">
          {bid.summary}
        </p>
      ) : null}
    </header>
  );
}
