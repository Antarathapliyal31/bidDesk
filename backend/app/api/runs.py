@router.post("/api/runs/{run_id}/bid/finalize")
async def finalize_run_bid(request: Request, run_id: str, body: dict[str, Any]) -> dict[str, Any]:
    from app.contracts.bid import Bid
    from app.contracts.errors import ApiError

    run = await repo.get_run(_db(request), run_id=run_id)
    if run is None:
        raise RunNotFoundError(run_id=run_id)
    draft_revision = body.get("draft_revision")
    if draft_revision is None or not isinstance(draft_revision, int):
        raise InvalidInputError("draft_revision (int) is required")

    draft = await repo.get_bid(_db(request), run_id=run_id, kind="draft")
    final = await repo.get_bid(_db(request), run_id=run_id, kind="final")
    # Idempotent: if the SAME revision is already finalised,
    # return the existing final.
    if final is not None and final["revision"] == draft_revision:
        return {"bid": final["data"]}
    if draft is None:
        raise InvalidInputError("no draft bid to finalize")
    if draft["revision"] != draft_revision:
        raise StaleRevisionError(current=draft["data"])

    bid = Bid.model_validate(draft["data"])
    if bid.totals.open_flags > 0:
        open_line_ids = [line.line_id for line in bid.lines if line.review.state.value == "open"]
        err = ApiError(
            ErrorCode.open_flags,
            "cannot finalize while open-review lines exist",
            details={"open_line_ids": open_line_ids},
        )
        raise err

    now = _now_iso()
    final_bid = bid.model_copy(update={"kind": "final"})
    await repo.insert_final_bid(
        _db(request),
        run_id=run_id,
        final=final_bid.model_dump(mode="json"),
        created_at=now,
        finalized_at=now,
    )
    return {"bid": final_bid.model_dump(mode="json")}


