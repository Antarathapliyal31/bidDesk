async def _save_uploaded_pdf(
    *, raw: bytes, filename: str, settings: Any, run_id: str
) -> tuple[Path, str, int]:
    """Validate PDF bytes + persist under `data/uploads/<run_id>.pdf`.

    Returns `(stored_path, sha256, page_count)`. Raises
    `PdfCorrupt` / `PdfEncrypted` / `TooLarge` / `empty_input` /
    `too_many_pages` as appropriate."""

    import pdfplumber
    from pdfminer.pdfparser import PDFSyntaxError

    size_mb = len(raw) / (1024 * 1024)
    if len(raw) == 0:
        raise EmptyInputError()
    if size_mb > settings.max_upload_mb:
        raise TooLargeError(size_mb=size_mb, limit_mb=float(settings.max_upload_mb))
    if not raw.startswith(b"%PDF-"):
        raise PdfCorruptError()

    uploads_dir = settings.app_db_path.parent / "uploads"
    uploads_dir.mkdir(parents=True, exist_ok=True)
    stored = uploads_dir / f"{run_id}.pdf"
    stored.write_bytes(raw)
    sha256 = hashlib.sha256(raw).hexdigest()

    try:
        with pdfplumber.open(stored) as pdf:
            page_count = len(pdf.pages)
    except PDFSyntaxError as exc:
        stored.unlink(missing_ok=True)
        raise PdfCorruptError() from exc
    except Exception as exc:  # pdfplumber wraps encrypted PDFs oddly
        stored.unlink(missing_ok=True)
        msg = str(exc).lower()
        if "encrypt" in msg or "password" in msg:
            raise PdfEncryptedError() from exc
        raise PdfCorruptError() from exc

    from app.config import get_settings as _cfg

    settings_now = _cfg()
    if page_count > settings_now.max_pages:
        stored.unlink(missing_ok=True)
        from app.contracts.errors import TooManyPagesError

        raise TooManyPagesError(page_count=page_count, max_pages=settings_now.max_pages)
    return stored, sha256, page_count


@router.post("/api/runs", status_code=201)
async def create_run(
    request: Request,
    branch_id: str = Form(...),
    text: str | None = Form(default=None),
    file: UploadFile | None = None,
    faults: str | None = Form(default=None),
) -> JSONResponse:
    """Start a run. Multipart body: file XOR text + branch_id +
    optional faults JSON. Returns 201 `{run_id}` and kicks the
    pipeline off as a background task."""

    settings = _settings(request)
    has_file = file is not None and (file.filename or "").strip() != ""
    has_text = text is not None and text.strip() != ""
    if has_file == has_text:
        # both or neither → invalid_input
        reason = "both file and text set" if has_file else "neither file nor text set"
        raise InvalidInputError(f"exactly one of file/text must be provided ({reason})")

    branch = await _get_branch(request, branch_id)
    run_id = _new_run_id()

    plan_kwargs: dict[str, Any]
    input_kind: InputKind
    input_name: str | None
    if has_file:
        assert file is not None  # mypy
        raw = await file.read()
        stored_path, sha256, page_count = await _save_uploaded_pdf(
            raw=raw, filename=file.filename or "", settings=settings, run_id=run_id
        )
        await repo.insert_run(
            _db(request),
            run_id=run_id,
            branch_id=branch_id,
            input_kind=InputKind.pdf,
            input_name=file.filename,
            created_at=_now_iso(),
        )
        await repo.insert_document(
            _db(request),
            run_id=run_id,
            filename=file.filename or "",
            sha256=sha256,
            page_count=page_count,
            stored_path=str(stored_path),
        )
        plan_kwargs = {
            "kind": "pdf",
            "pdf_path": str(stored_path),
            "pasted_text": None,
        }
        input_kind = InputKind.pdf
        input_name = file.filename
    else:
        assert text is not None  # mypy
        if len(text) > settings.max_text_chars:
            raise TextTooLongError(count=len(text), limit=settings.max_text_chars)
        await repo.insert_run(
            _db(request),
            run_id=run_id,
            branch_id=branch_id,
            input_kind=InputKind.text,
            input_name="pasted",
            created_at=_now_iso(),
        )
        plan_kwargs = {
            "kind": "text",
            "pdf_path": None,
            "pasted_text": text,
        }
        input_kind = InputKind.text
        input_name = "pasted"

    # Faults: parse + gate behind demo flag.
    if faults is not None and faults.strip() not in ("", "[]"):
        if not settings.demo_faults_enabled:
            raise InvalidInputError("faults supplied but demo_faults_enabled=false")
        try:
            parsed = json.loads(faults)
        except json.JSONDecodeError as exc:
            raise InvalidInputError(f"faults is not valid JSON: {exc}") from exc
        if not isinstance(parsed, list):
            raise InvalidInputError("faults must be a JSON array")

    plan = RunPlan(
        branch_id=branch_id,
        document_tag=f"document_{run_id}",
        **plan_kwargs,
    )

    await start_pipeline(
        inputs=PipelineInputs(run_id=run_id, branch=branch, plan=plan),
        db=_db(request),
        bus=_bus(request),
        settings=settings,
        bundle=_bundle(request),
        registry=_registry(request),
    )
    _ = input_kind, input_name  # fields reserved for list payload
    return JSONResponse(status_code=201, content={"run_id": run_id})


