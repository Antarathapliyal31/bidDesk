@router.patch("/api/runs/{run_id}/bid")
async def patch_run_bid(request: Request, run_id: str, body: EditRequest) -> dict[str, Any]:
    """Atomic edit: read + check + apply + replace + audit all
    land inside ONE `db.write()` transaction via
    `repo.apply_patch_atomically`. Two concurrent PATCHes on the
    same revision are serialised by the write lock; exactly one
    bumps the revision, the other sees `StaleRevisionConflict` and
    gets 409."""

    from app.bid.edits import EditOpError, apply_edits
    from app.contracts.bid import Bid
    from app.db.repo import StaleRevisionConflict

    run = await repo.get_run(_db(request), run_id=run_id)
    if run is None:
        raise RunNotFoundError(run_id=run_id)

    catalog_db = _settings(request).catalog_db_path

    def _catalog_lookup(sku: str) -> dict[str, Any] | None:
        import sqlite3

        conn = sqlite3.connect(f"file:{catalog_db}?mode=ro", uri=True)
        try:
            row = conn.execute(
                "SELECT sku, name, sale_unit, unit_price_cents "
                "FROM products WHERE sku = ? AND active = 1",
                (sku,),
            ).fetchone()
        finally:
            conn.close()
        if row is None:
            return None
        return {
            "sku": row[0],
            "product_name": row[1],
            "sale_unit": row[2],
            "unit_price_cents": int(row[3]),
        }

    op_error: dict[str, Any] = {}

    def _apply(current_data: dict[str, Any]) -> tuple[dict[str, Any], list[dict[str, Any]]]:
        current = Bid.model_validate(current_data)
        try:
            new_bid, audit = apply_edits(
                current,
                body,
                catalog_lookup=_catalog_lookup,
                now_iso=_now_iso(),
            )
        except EditOpError as exc:
            # Stash the error for the outer handler; we raise the
            # 422 OUTSIDE the transaction so the exception doesn't
            # roll back a legitimate txn (there's nothing to roll
            # back here, but keep the pattern clean).
            op_error.update({"index": exc.index, "op_kind": exc.op_kind, "message": exc.message})
            raise
        return new_bid.model_dump(mode="json"), audit

    try:
        new_data = await repo.apply_patch_atomically(
            _db(request),
            run_id=run_id,
            expected_draft_revision=body.draft_revision,
            apply=_apply,
            created_at=_now_iso(),
        )
    except StaleRevisionConflict as exc:
        raise StaleRevisionError(current=exc.current) from exc
    except EditOpError as exc:
        # The transaction aborted cleanly (no writes landed before
        # the raise). Render 422 with per-op details.
        raise ApiError(
            ErrorCode.invalid_input,
            exc.message,
            details={"ops": [{"index": exc.index, "op": exc.op_kind, "error": exc.message}]},
        ) from exc

    _ = op_error  # unused outside the exception path
    return {"bid": new_data}


